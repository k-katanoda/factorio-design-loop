#!/usr/bin/env python3
"""Verify that the selected immutable candidate matches its patch and reports."""
from __future__ import annotations
import copy, hashlib, json
from pathlib import Path
from loop import load, encode, patch_data, inspect, diff_data, viewer_links

ROOT = Path(__file__).resolve().parent

def check() -> str:
    current = json.loads((ROOT/'revisions/current.json').read_text(encoding='utf-8'))
    rev = current['revision']
    if not rev.startswith('r') or '/' in rev or '..' in rev:
        raise ValueError('Invalid revision pointer')
    folder = ROOT/'revisions'/rev
    base = load(ROOT/'designs/nuclear_baseline.txt')
    actual = load(folder/'blueprint.txt')
    patch = json.loads((ROOT/'designs/water_patch_proposal.json').read_text(encoding='utf-8'))
    candidate, changes = patch_data(copy.deepcopy(base), patch)
    if candidate != actual:
        raise AssertionError('Current revision is not generated by the approved base+patch')
    manifest = json.loads((folder/'manifest.json').read_text(encoding='utf-8'))
    if manifest['base_sha256'] != hashlib.sha256(encode(base).encode()).hexdigest():
        raise AssertionError('Baseline hash mismatch')
    if manifest['blueprint_sha256'] != hashlib.sha256(encode(actual).encode()).hexdigest():
        raise AssertionError('Candidate hash mismatch')
    validation = inspect(actual)
    if validation['status'] != 'PASS_STATIC_LIMITED' or manifest['gate'] != 'STATIC_PASS_GAME_NOT_TESTED':
        raise AssertionError('Candidate did not pass the LIMITED static validation gate')
    expected = {
        'validation.json': validation,
        'baseline-validation.json': inspect(base),
        'diff.json': diff_data(base, actual),
        'viewer_urls.json': viewer_links(actual),
    }
    for name, value in expected.items():
        saved = json.loads((folder/name).read_text(encoding='utf-8'))
        if saved != value:
            raise AssertionError(f'Stale or inconsistent artifact: {name}')
    if manifest['operation_count'] != len(changes):
        raise AssertionError('Patch operation count mismatch')
    return rev

if __name__ == '__main__':
    print('Verified immutable revision:', check())
